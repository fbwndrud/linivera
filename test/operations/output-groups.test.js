import test from 'node:test';
import assert from 'node:assert/strict';
import { productionFixture } from './production-fixture.js';
import { inspectExecution } from '../../core/operations/executions.js';
import { recordGroupReview, decideGroupPublication } from '../../core/operations/group-publications.js';
import { readWorkspaceState } from '../../core/publications/state.js';
import { queryResourceGraph } from '../../core/query/resource-graph.js';
import { metadataEntries, buildMetadataProjection } from '../../core/projections/metadata.js';
import { observeGroups } from './group-fixture.js';
test('one candidate hard finding does not block a separately reviewed candidate and partial groups cannot publish', async (t) => {
  const f = await productionFixture(t); const run = await observeGroups(f);
  const a = await run.submit('A'); const b = await run.submit('B');
  assert.deepEqual((await inspectExecution(f.root, { operationId: b.operationId })).submittedGroups.map((group) => group.groupId).sort(), ['A', 'B']);
  assert.equal(b.outputs.length, 2, 'manifest and artifact are both reviewed');
  const hard = await recordGroupReview(f.root, { operationId: a.operationId, groupId: 'A', outputHashes: a.outputs.map((output) => output.contentHash), reviewer: 'host', findings: [{ severity: 'hard', message: 'synthetic hard' }] });
  const checkpoint = (await readWorkspaceState(f.root)).checkpoint;
  await assert.rejects(decideGroupPublication(f.root, { operationId: a.operationId, groupId: 'A', receiptId: hard, expectedCheckpoint: checkpoint, actor: 'user', action: 'approve' }), { code: 'APPROVE_BLOCKED_BY_HARD' });
  const receiptId = await recordGroupReview(f.root, { operationId: b.operationId, groupId: 'B', outputHashes: b.outputs.map((output) => output.contentHash), reviewer: 'host', findings: [{ severity: 'soft', message: 'synthetic soft' }] });
  const decision = { operationId: b.operationId, groupId: 'B', receiptId, expectedCheckpoint: checkpoint, actor: 'user', action: 'approve' };
  const publication = await decideGroupPublication(f.root, decision);
  assert.equal(publication.selfReview, true);
  assert.deepEqual(await decideGroupPublication(f.root, decision), publication);
  assert.equal((await readWorkspaceState(f.root)).groupPublications.length, 1);
  const entries = await metadataEntries(f.root, await readWorkspaceState(f.root));
  assert.equal(entries.filter((entry) => entry.groupId === 'B').length, 2);
  assert.equal(entries.filter((entry) => entry.groupId === 'A').length, 0);
  await buildMetadataProjection(f.root);
  const graph = await queryResourceGraph(f.root, { resourceId: 'B' });
  assert.ok(graph.nodes.find((node) => node.revisionId === b.resultRevisionIds[0]).states.includes('approved'));
  await assert.rejects(run.submit('C'), { code: 'OUTPUT_GROUP_INVALID' });
  await run.event({ type: 'outputs-observed', artifacts: [run.artifacts[0]] });
  assert.equal((await inspectExecution(f.root, { operationId: b.operationId })).executions[0].artifacts.length, 2);
  assert.deepEqual(await decideGroupPublication(f.root, decision), publication, 'later observations do not invalidate a sealed group prefix');
  const late = await f.resource('late', 'result', 'synthetic late output', 'text/plain');
  await run.event({ type: 'outputs-observed', artifacts: [{ artifactKey: 'B/late', groupId: 'B', role: 'image', revisionId: late.revisionId }] });
  const laterGraph = await queryResourceGraph(f.root, { resourceId: 'late' });
  assert.ok(!laterGraph.nodes.find((node) => node.revisionId === late.revisionId).states.includes('approved'), 'publication covers exact bytes, not future artifacts sharing a group label');
});
test('a candidate cannot borrow another candidate artifact or a stale execution prefix', async (t) => {
  const f = await productionFixture(t); const run = await observeGroups(f);
  const foreign = run.artifacts[1];
  const manifest = await f.resource('mixed', 'production-group', { version: 1, groupId: 'A', members: [{ artifactKey: foreign.artifactKey, role: foreign.role, revisionId: foreign.revisionId }] });
  await assert.rejects(run.submit('A', { groupManifestRevisionId: manifest.revisionId, resultRevisionIds: [foreign.revisionId] }), { code: 'OUTPUT_GROUP_INVALID' });
  await assert.rejects(run.submit('B', { executionHead: { seq: 99, hash: 'sha256:' + '0'.repeat(64) } }), { code: 'EXECUTION_HEAD_INVALID' });
  const b = await run.submit('B');
  await assert.rejects(recordGroupReview(f.root, { operationId: b.operationId, groupId: 'B', outputHashes: b.outputs.map((output) => output.contentHash), reviewer: 'user', findings: [], selfReview: false }), { code: 'REVIEW_INVALID' });
});
